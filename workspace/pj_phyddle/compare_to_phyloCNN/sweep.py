def load_base_config(path):
    """Run a phyddle config file and return its `args` dict."""
    ns = {}
    with open(path) as f:
        exec(compile(f.read(), path, 'exec'), ns)
    if 'args' not in ns or not isinstance(ns['args'], dict):
        sys.exit(f'{path} does not define a dict called args')
    return dict(ns['args'])


def write_config(path, args):
    """Write a phyddle config file (args = {...})."""
    tmp = path + '.tmp'
    with open(tmp, 'w') as f:
        f.write('# generated by sweep.py - do not edit, re-run the sweep instead\n')
        f.write('args = ' + pprint.pformat(args, width=100, sort_dicts=False) + '\n')
    os.replace(tmp, path)


def write_json(path, obj):
    tmp = path + '.tmp'
    with open(tmp, 'w') as f:
        json.dump(obj, f, indent=2, default=str)
    os.replace(tmp, path)


def read_json(path):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def data_name(d):
    return os.path.basename(d.rstrip('/'))


def norm_dir(d):
    return d.rstrip('/')


@contextmanager
def file_lock(path):
    """Exclusive lock (so two shards never format the same folder at once)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)


def tail(path, n=30):
    try:
        with open(path, errors='replace') as f:
            return ''.join(f.readlines()[-n:])
    except OSError:
        return ''


def phyddle_cmd(cmd_template, cfg_path):
    return [c.format(cfg=cfg_path) for c in shlex.split(cmd_template)]


def run_phyddle(cmd_template, cfg_path, log_path, env=None):
    """Run phyddle on a config file (blocking), appending output to log_path."""
    cmd = phyddle_cmd(cmd_template, cfg_path)
    with open(log_path, 'a') as log:
        log.write(f'\n===== {time.strftime("%Y-%m-%d %H:%M:%S")}  {" ".join(cmd)}\n')
        log.flush()
        proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT, env=env,
                                start_new_session=True)
        try:
            rc = proc.wait()
            signal_group(proc, signal.SIGKILL)   # no stray workers after it ends
            return rc
        except KeyboardInterrupt:
            stop_process(proc)
            raise


def start_phyddle(cmd_template, cfg_path, log_path, env=None):
    """Start phyddle on a config file without waiting. Returns (Popen, log handle)."""
    cmd = phyddle_cmd(cmd_template, cfg_path)
    log = open(log_path, 'a')
    log.write(f'\n===== {time.strftime("%Y-%m-%d %H:%M:%S")}  {" ".join(cmd)}\n')
    log.flush()
    proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT, env=env,
                            start_new_session=True)   # Ctrl-C goes to the sweep only
    return proc, log


def signal_group(proc, sig):
    """Send a signal to a phyddle process and everything it started (its
    multiprocessing workers, R). Processes started by start_phyddle lead their
    own process group, so the whole group is signalled; otherwise only proc."""
    try:
        if os.getpgid(proc.pid) == proc.pid:
            os.killpg(proc.pid, sig)
        else:
            proc.send_signal(sig)
    except (ProcessLookupError, PermissionError):
        pass


def stop_process(proc, timeout=60):
    """Ask a phyddle process and its workers to stop (SIGTERM); kill them if
    they do not stop within timeout seconds."""
    if proc.poll() is None:
        signal_group(proc, signal.SIGTERM)
        try:
            proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            signal_group(proc, signal.SIGKILL)
            proc.wait()
    # workers can outlive the main process; make sure none are left
    signal_group(proc, signal.SIGKILL)


def describe_exit(rc):
    """Readable description of a process exit code."""
    if rc is None:
        return 'did not finish'
    if rc >= 0:
        return f'exited with code {rc}'
    try:
        name = signal.Signals(-rc).name
    except ValueError:
        name = f'signal {-rc}'
    hint = ''
    if -rc == signal.SIGKILL:
        hint = (' - nothing in the log usually means the system ran out of memory '
                '(check: dmesg -T | grep -i -E "out of memory|killed process")')
    elif -rc == signal.SIGTERM:
        hint = ' - stopped by the sweep (Ctrl-C / kill) or by the system'
    return f'was killed by {name}{hint}'


def note_exit(log_path, rc):
    """Append how the process ended to its log (phyddle cannot do this itself
    when it is killed)."""
    try:
        with open(log_path, 'a') as log:
            log.write(f'\n===== {time.strftime("%Y-%m-%d %H:%M:%S")}  phyddle {describe_exit(rc)}\n')
    except OSError:
        pass


def child_env(gpu=None, mem_fraction=None, threads=None):
    """Environment for a phyddle process: which GPU it sees, its GPU memory
    fraction (read by train.py) and its CPU thread count."""
    env = dict(os.environ)
    if gpu is not None:
        env['CUDA_VISIBLE_DEVICES'] = str(gpu)
    if mem_fraction is not None:
        env['PHYDDLE_GPU_MEM_FRACTION'] = f'{mem_fraction:.3f}'
    if threads is not None:
        for k in ('OMP_NUM_THREADS', 'MKL_NUM_THREADS', 'OPENBLAS_NUM_THREADS'):
            env[k] = str(threads)
    return env


