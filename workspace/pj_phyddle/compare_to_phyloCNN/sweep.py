def run_paths(out, run_id):
    rdir = os.path.join(out, 'runs', run_id)
    return {'dir': rdir,
            'trn_dir': os.path.join(rdir, 'train'),
            'cfg': os.path.join(rdir, 'config_train.py'),
            'log': os.path.join(rdir, 'train.log'),
            'status': os.path.join(rdir, 'status.json'),
            'metrics': os.path.join(rdir, 'train', 'metrics.json')}


def run_status(out, run):
    p = run_paths(out, run['run_id'])
    if os.path.exists(p['metrics']):
        return 'done'
    st = read_json(p['status'])
    if st is None:
        return 'pending'
    if st.get('state') == 'failed':
        return 'failed'
    if st.get('state') == 'running' and pid_alive(st.get('pid')):
        return 'running'     # still being trained by another (or an orphaned) process
    return 'resumable'   # interrupted: resumes from checkpoint.tar


def pid_alive(pid):
    if not pid:
        return False
    try:
        os.kill(int(pid), 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def claim_run(out, run_id):
    """Lock a run for this sweep process, so two sweep processes on the same
    --out folder never train the same run. Returns the lock handle, or None if
    another process holds it. The lock is released when the handle is closed
    or the process exits."""
    fh = open(os.path.join(out, 'locks', f'{run_id}.lock'), 'w')
    try:
        fcntl.flock(fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        fh.close()
        return None
    return fh


def release(fh):
    if fh is not None:
        try:
            fcntl.flock(fh, fcntl.LOCK_UN)
        finally:
            fh.close()


def prepare_train(out, base_args, run, overrides=None, extra_status=None):
    """Write the Train config and a 'running' status. Returns the run paths."""
    p = run_paths(out, run['run_id'])
    os.makedirs(p['trn_dir'], exist_ok=True)
    args = dict(base_args)
    args.update(FIXED)
    args.update(data_settings(run['dir'], run['K']))
    args.update(TRAIN_EXTRA)
    args.update({'step': 'T',
                 'trn_dir': p['trn_dir'],
                 'subtree_pool': run['subtree_pool'],
                 'phylo_pool': run['phylo_pool'],
                 'n_parts': run['n_parts']})
    args.update(overrides or {})
    write_config(p['cfg'], args)
    status = {'run': run, 'state': 'running', 'started': time.strftime('%Y-%m-%d %H:%M:%S')}
    status.update(extra_status or {})
    write_json(p['status'], status)
    return p


def finish_train(out, run, rc, seconds, interrupted=False):
    """Record the outcome of a Train run. Returns True if it finished."""
    p = run_paths(out, run['run_id'])
    note_exit(p['log'], rc if not interrupted else -signal.SIGTERM)
    status = read_json(p['status']) or {'run': run}
    status['seconds'] = round(seconds, 1)
    if interrupted:
        status['state'] = 'interrupted'
        write_json(p['status'], status)
        return False
    metrics = read_json(p['metrics'])
    if rc == 0 and metrics is not None:
        problems = []
        if metrics.get('max_model_states') != run['K']:
            problems.append(f"max_model_states in metrics.json is {metrics.get('max_model_states')}")
        if metrics.get('num_classes') != run['K']:
            problems.append(f"num_classes is {metrics.get('num_classes')}, expected {run['K']}")
        status.update(state='done', warnings=problems)
        write_json(p['status'], status)
        for w in problems:
            print(f'    ! {run["run_id"]}: {w}', flush=True)
        return True
    if rc == 0:
        msg = (f'phyddle finished but {p["metrics"]} was not written - check that '
               f'trn_dir is honoured and train.py is the updated version')
    else:
        msg = f'phyddle {describe_exit(rc)}'
    status.update(state='failed', error=msg, log_tail=tail(p['log']))
    write_json(p['status'], status)
    print(f'    ✗ {run["run_id"]}: {msg}; see {p["log"]}', flush=True)
    return False


def train_run(out, base_args, run, cmd):
    """Run one Train job (blocking)."""
    p = prepare_train(out, base_args, run, extra_status={'pid': os.getpid()})
    t0 = time.time()
    try:
        rc = run_phyddle(cmd, p['cfg'], p['log'])
    except KeyboardInterrupt:
        finish_train(out, run, None, time.time() - t0, interrupted=True)
        raise
    return finish_train(out, run, rc, time.time() - t0)

