def detect_gpus():
    """GPU ids visible to this process (CUDA_VISIBLE_DEVICES or nvidia-smi)."""
    cvd = os.environ.get('CUDA_VISIBLE_DEVICES')
    if cvd is not None and cvd.strip() not in ('', '-1'):
        return [g.strip() for g in cvd.split(',') if g.strip()]
    try:
        res = subprocess.run(['nvidia-smi', '-L'], capture_output=True, text=True, timeout=30)
        n = sum(1 for ln in res.stdout.splitlines() if ln.startswith('GPU '))
        return [str(i) for i in range(n)]
    except (OSError, subprocess.SubprocessError):
        return []


def plan_resources(a, n_folders_to_format):
    """Decide GPU slots, GPU memory fractions and CPU counts for --jobs."""
    gpus = [g.strip() for g in a.gpus.split(',')] if a.gpus else detect_gpus()
    if not gpus:
        sys.exit('No GPUs found; pass --gpus 0,1,2,3')
    jobs = a.jobs if a.jobs > 0 else len(gpus)
    slots = [gpus[i % len(gpus)] for i in range(jobs)]          # round-robin over GPUs
    per_gpu = {g: slots.count(g) for g in gpus}
    # one job on a GPU keeps train.py's 0.8; several share 0.9 of it
    mem = {g: (a.mem_fraction if a.mem_fraction else
               (0.8 if n == 1 else round(0.9 / n, 3)))
           for g, n in per_gpu.items() if n > 0}

    cpus = a.cpus if a.cpus else max(1, (os.cpu_count() or 1) - 2)
    format_jobs = max(0, min(a.format_jobs, n_folders_to_format))
    if a.train_threads:
        train_threads = a.train_threads
    else:
        # half the CPUs for training while Format runs, at least 2 and at most 8 each
        share = cpus // 2 if format_jobs else cpus
        train_threads = max(2, min(8, share // jobs))
    if a.format_procs:
        format_procs = a.format_procs
    else:
        # at most 16: each Format worker runs its own R session, so many
        # workers need a lot of RAM (too many -> the system kills Format)
        format_procs = max(2, min(16, (cpus - jobs * train_threads) // max(format_jobs, 1)))
    return {'gpus': gpus, 'slots': slots, 'mem': mem, 'cpus': cpus, 'jobs': jobs,
            'format_jobs': format_jobs, 'train_threads': train_threads,
            'format_procs': format_procs}


def run_parallel(out, base_args, runs, all_runs, a):
    """Run Format and Train jobs concurrently:
    - up to --jobs Train runs, spread over the GPUs (one CUDA device each);
    - up to --format-jobs Format runs (CPU), at most one per data folder,
      started as soon as possible so training can begin on finished folders.
    """
    todo = []
    for r in runs:
        st = run_status(out, r)
        if st in ('done', 'running') or (st == 'failed' and not a.retry_failed):
            if st == 'running':
                print(f"▪ {r['run_id']} is being trained by another process; skipping")
            continue
        todo.append(r)
    if not todo:
        print('▪ Nothing to run.')
        return

    need_fmt = list(dict.fromkeys((r['dir'], r['K']) for r in todo
                                  if not format_done(out, base_args, r['dir'], r['K'])))
    res = plan_resources(a, len({d for d, _ in need_fmt}))
    print(f"▪ {len(todo)} training runs, {len(need_fmt)} Format runs")
    gpu_desc = ', '.join(f"GPU {g}: {res['slots'].count(g)} job(s), mem fraction {res['mem'][g]}"
                         for g in res['gpus'] if g in res['mem'])
    print(f"▪ GPUs {','.join(res['gpus'])}: {res['jobs']} training jobs ({gpu_desc})")
    print(f"▪ CPUs {res['cpus']}: {res['train_threads']} threads per training job, "
          f"{res['format_jobs']} Format job(s) at a time with num_proc = {res['format_procs']}")

    train_over = {'num_proc': res['train_threads'], 'use_cuda': 'T'}
    fmt_over = {'num_proc': res['format_procs']}

    running_fmt = {}      # data dir -> dict(proc, log, lock, key, t0)
    running_trn = {}      # slot index -> dict(proc, log, run, t0)
    fmt_failed = {}       # (dir, K) -> message
    last_plot = 0.0

    def can_train(r):
        return (r['dir'], r['K']) not in fmt_failed and format_done(out, base_args, r['dir'], r['K'])

    try:
        while todo or running_fmt or running_trn:
            # --- finished Format jobs
            for d in list(running_fmt):
                job = running_fmt[d]
                rc = job['proc'].poll()
                if rc is None:
                    continue
                signal_group(job['proc'], signal.SIGKILL)   # leftover workers
                job['log'].close()
                fcntl.flock(job['lock'], fcntl.LOCK_UN)
                job['lock'].close()
                ok, msg = finish_format(out, base_args, d, job['key'][1], rc, time.time() - job['t0'])
                print(f"  {'✓' if ok else '✗'} Format {data_name(d)} K={job['key'][1]}: {msg}",
                      flush=True)
                if not ok:
                    fmt_failed[job['key']] = msg
                del running_fmt[d]

            # --- finished Train jobs
            finished_any = False
            for slot in list(running_trn):
                job = running_trn[slot]
                rc = job['proc'].poll()
                if rc is None:
                    continue
                signal_group(job['proc'], signal.SIGKILL)   # leftover workers
                job['log'].close()
                r = job['run']
                ok = finish_train(out, r, rc, time.time() - job['t0'])
                release(job['claim'])
                if ok:
                    m = read_json(run_paths(out, r['run_id'])['metrics']) or {}
                    print(f"  ✓ {r['run_id']} (GPU {res['slots'][slot]}): best epoch "
                          f"{m.get('best_epoch')}  val acc {m.get('best_val_acc')}  "
                          f"test acc {m.get('test_acc')}", flush=True)
                del running_trn[slot]
                finished_any = True

            # --- drop runs whose Format failed
            for r in [r for r in todo if (r['dir'], r['K']) in fmt_failed]:
                print(f"  - skipping {r['run_id']}: Format failed", flush=True)
                todo.remove(r)
            need_fmt = [k for k in need_fmt if k not in fmt_failed
                        and not format_done(out, base_args, *k)]

            # --- start Format jobs (one per data folder, up to format_jobs)
            for key in need_fmt:
                d, K = key
                if len(running_fmt) >= res['format_jobs']:
                    break
                if d in running_fmt:
                    continue
                lock = open(os.path.join(out, 'locks', f'{data_name(d)}.format.lock'), 'w')
                try:
                    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
                except OSError:          # another sweep process is formatting this folder
                    lock.close()
                    continue
                if format_done(out, base_args, d, K):
                    fcntl.flock(lock, fcntl.LOCK_UN)
                    lock.close()
                    continue
                cfg_fn, log_fn = prepare_format(out, base_args, d, K, fmt_over)
                proc, log = start_phyddle(a.phyddle_cmd, cfg_fn, log_fn,
                                          env=child_env(gpu='', threads=1))
                running_fmt[d] = {'proc': proc, 'log': log, 'lock': lock, 'key': key,
                                  't0': time.time()}
                print(f'  ▸ Format {data_name(d)} K={K} started (log: {log_fn})', flush=True)

            # --- start Train jobs on free slots
            for slot, gpu in enumerate(res['slots']):
                if slot in running_trn:
                    continue
                r = next((r for r in todo if can_train(r)), None)
                if r is None:
                    break
                todo.remove(r)
                claim = claim_run(out, r['run_id'])
                if claim is None:
                    print(f"  - {r['run_id']} is claimed by another sweep process; skipping",
                          flush=True)
                    continue
                if run_status(out, r) in ('done', 'running'):
                    release(claim)
                    continue
                resumed = run_status(out, r) == 'resumable'
                p = prepare_train(out, base_args, r, train_over,
                                  extra_status={'gpu': gpu, 'pid': None})
                proc, log = start_phyddle(a.phyddle_cmd, p['cfg'], p['log'],
                                          env=child_env(gpu, res['mem'][gpu], res['train_threads']))
                st = read_json(p['status'])
                st['pid'] = proc.pid
                write_json(p['status'], st)
                running_trn[slot] = {'proc': proc, 'log': log, 'run': r, 't0': time.time(),
                                     'claim': claim}
                print(f"  ▸ {r['run_id']} on GPU {gpu} ({'resuming' if resumed else 'new'}); "
                      f"{len(todo)} waiting", flush=True)

            # --- nothing running and nothing can start: waiting on another process's Format
            if not running_fmt and not running_trn and todo and not need_fmt:
                print('▪ Remaining runs wait for Format runs that failed or are locked; stopping.')
                break

            if finished_any and time.time() - last_plot > a.plot_every * 60:
                try:
                    make_plots(out, all_runs)
                except Exception:
                    traceback.print_exc()
                last_plot = time.time()
            time.sleep(5)
    except KeyboardInterrupt:
        print('\nInterrupted - stopping jobs (each training run keeps its last epoch checkpoint)...',
              flush=True)
        for job in list(running_trn.values()) + list(running_fmt.values()):
            signal_group(job['proc'], signal.SIGTERM)
        for job in list(running_trn.values()):
            stop_process(job['proc'])
            job['log'].close()
            finish_train(out, job['run'], None, time.time() - job['t0'], interrupted=True)
            release(job['claim'])
        for job in running_fmt.values():
            stop_process(job['proc'])
            job['log'].close()
        print('Run the same command again to resume.')
        sys.exit(130)

