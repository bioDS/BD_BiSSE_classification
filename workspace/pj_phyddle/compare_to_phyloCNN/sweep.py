def collect(out, runs):
    import pandas as pd
    rows = []
    for run in runs:
        p = run_paths(out, run['run_id'])
        m = read_json(p['metrics'])
        if m is None:
            continue
        row = {k: run[k] for k in ('run_id', 'data', 'K', 'subtree_pool', 'phylo_pool',
                                   'n_parts', 'variant')}
        for k in ('epochs_run', 'stopped_early', 'stop_reason', 'best_epoch',
                  'best_val_loss', 'best_val_acc', 'train_loss_at_best',
                  'train_acc_at_best', 'final_val_loss', 'final_val_acc',
                  'test_n', 'test_loss', 'test_acc', 'test_balanced_acc',
                  'test_macro_f1', 'n_train', 'n_val', 'run_seconds'):
            row[k] = m.get(k)
        for name, pc in (m.get('test_per_class') or {}).items():
            row[f'recall_{name}'] = pc.get('recall')
        rows.append(row)
    return pd.DataFrame(rows)


def load_history(out, run_id):
    import pandas as pd
    fn = os.path.join(run_paths(out, run_id)['trn_dir'], 'history.csv')
    if not os.path.exists(fn):
        return None
    h = pd.read_csv(fn)
    return h.pivot_table(index='epoch', columns=['dataset', 'metric'], values='value')


