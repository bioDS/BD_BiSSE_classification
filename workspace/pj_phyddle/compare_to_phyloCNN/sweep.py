#!/usr/bin/env python
"""
sweep.py - resumable grid of phyddle Format + Train runs, with summaries
and comparison plots.

Grid (edit GRID below):
    dir              : 3 simulation folders
    max_model_states : 2, 3, 4, 5          (num_states is set to the same value)
    pooling          : subtree F / phylo T,  both T,  both F
    n_parts          : 4, 8, 16            (for every pooling option)
    num_epochs = 200, fixed_split = True

Each data folder D gets packed_in_dir = D, packed_out_dir = D/simulate and
fmt_dir = D/format. Format runs once per (D, max_model_states); its HDF5
files carry a .states<K> tag, so they never overwrite each other.
Each training run gets its own folder <out>/runs/<run_id>/train.

Checkpointing / resuming
    * A run that finished (metrics.json written) is never re-run.
    * A run that was interrupted continues from its last epoch
      (train.py: resume_training = T, checkpoint.tar after every epoch).
    * Format is skipped for (D, K) once its marker file exists.
    * Runs that failed are skipped on later calls unless --retry-failed.
    Just run the same command again after a crash, reboot or Ctrl-C.

Usage
    python sweep.py --base-config config.py --out sweep_out            # run / resume
    python sweep.py --base-config config.py --out sweep_out --dry-run  # list runs + status
    python sweep.py --base-config config.py --out sweep_out --plot-only
    python sweep.py ... --only 'wide_priors.*K3'      # regex on run ids
    python sweep.py ... --jobs 0                      # one training run per GPU, all GPUs
    python sweep.py ... --jobs 4 --gpus 0,1,2,3       # the same, explicitly
    python sweep.py ... --jobs 8 --gpus 0,1,2,3       # two runs per GPU (memory fraction 0.45)
    python sweep.py ... --shard 0/2                   # or: split runs over separate processes

Parallel mode (--jobs)
    One sweep process starts and watches all phyddle processes:
    * training runs: each sees one GPU (CUDA_VISIBLE_DEVICES), GPU memory
      fraction 0.8 (one run per GPU) or 0.9 / runs-per-GPU, and
      num_proc / OMP threads = its share of --cpus;
    * Format runs: up to --format-jobs at a time (at most one per data
      folder), CPU only, num_proc = the CPUs left over from training.
    Training starts on a folder / K as soon as its Format has finished.
    Ctrl-C stops all jobs cleanly; run the same command again to resume.

Outputs in <out>/
    runs/<run_id>/config_train.py, train.log, status.json, train/ (all Train
        output, incl. history.csv, metrics.json, test_predictions.csv,
        test_confusion.csv, checkpoint.tar, best_checkpoint.tar)
    format/<data>__K<K>.log, .done.json, config_format.py
    summary.csv                 one row per finished run
    plots/*.png                 comparison plots
"""

