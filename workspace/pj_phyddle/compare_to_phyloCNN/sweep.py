def variant_label(sub, phy, n_parts, vary_n_parts=True):
    s = f'sub={sub} phy={phy}'
    if vary_n_parts:
        s += f' np={n_parts}'
    return s


def make_runs():
    """All (data dir, K, pooling, n_parts) combinations as dicts."""
    runs = []
    for d, K, (sub, phy) in itertools.product(GRID['dir'], GRID['max_model_states'],
                                              GRID['pooling']):
        vary = True
        for n_parts in GRID['n_parts']:
            np_tag = f'np{n_parts}'
            run_id = f'{data_name(d)}__K{K}__sub{sub}_phy{phy}__{np_tag}'
            runs.append({'run_id': run_id, 'dir': norm_dir(d), 'data': data_name(d),
                         'K': K, 'subtree_pool': sub, 'phylo_pool': phy,
                         'n_parts': n_parts, 'vary_n_parts': vary,
                         'variant': variant_label(sub, phy, n_parts, vary)})
    return runs


def data_settings(d, K):
    """Settings shared by Format and Train for data folder d and K states."""
    return {
        'dir':              d + '/',
        'packed_in_dir':    d + '/',
        'packed_out_dir':   d + '/simulate',
        'sim_dir':          d + '/simulate',
        'fmt_dir':          d + '/format',
        'max_model_states': K,
        'num_states':       K,
        'num_classes':      K,   # BD, BiSSE, MuSSE_3..K
    }

