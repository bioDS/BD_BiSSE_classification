def format_paths(out, data, K):
    base = os.path.join(out, 'format', f'{data}__K{K}')
    return base + '.done.json', base + '.log', base + '.config.py'


def expected_hdf5(base_args, d, K):
    prefix = base_args.get('prefix', 'out')
    enc = re.sub(r'[^A-Za-z0-9_\-]+', '_', str(base_args.get('encoding_type', 'default')))
    return [f'{d}/format/{prefix}.{s}.{enc}.states{K}.hdf5' for s in ('train', 'test')]


def format_done(out, base_args, d, K):
    done_fn = format_paths(out, data_name(d), K)[0]
    return (read_json(done_fn) is not None and
            all(os.path.exists(f) for f in expected_hdf5(base_args, d, K)))


def prepare_format(out, base_args, d, K, overrides=None):
    """Write the Format config for (d, K); returns (config path, log path)."""
    done_fn, log_fn, cfg_fn = format_paths(out, data_name(d), K)
    os.makedirs(os.path.dirname(done_fn), exist_ok=True)
    args = dict(base_args)
    args.update(FIXED)
    args.update(data_settings(d, K))
    args['step'] = 'F'
    args.update(overrides or {})
    write_config(cfg_fn, args)
    return cfg_fn, log_fn


def finish_format(out, base_args, d, K, rc, seconds):
    """Check a finished Format run and write its marker. Returns (ok, message)."""
    done_fn, log_fn, _ = format_paths(out, data_name(d), K)
    files = expected_hdf5(base_args, d, K)
    note_exit(log_fn, rc)
    if rc != 0:
        return False, f'Format {describe_exit(rc)}; see {log_fn}'
    if f'max_model_states = {K}' not in tail(log_fn, 10**9):   # whole log; the line is near the top
        return False, (f'Format log has no "max_model_states = {K}" line, so the setting '
                       f'was probably not passed through by phyddle (register it with '
                       f'the other custom settings); see {log_fn}')
    missing = [f for f in files if not os.path.exists(f)]
    if missing:
        return False, f'Format finished but {missing} are missing; see {log_fn}'
    write_json(done_fn, {'dir': d, 'K': K, 'files': files, 'seconds': round(seconds, 1),
                         'finished': time.strftime('%Y-%m-%d %H:%M:%S')})
    return True, 'format finished'


def ensure_format(out, base_args, d, K, cmd, dry_run=False, overrides=None, env=None):
    """Run Format for (d, K) unless it is done (blocking). Returns (ok, message)."""
    if format_done(out, base_args, d, K):
        return True, 'format already done'
    if dry_run:
        return True, 'format needed'
    # one lock per data folder: Format unpacks into <d>/simulate for every K
    with file_lock(os.path.join(out, 'locks', f'{data_name(d)}.format.lock')):
        if format_done(out, base_args, d, K):
            return True, 'format done by another sweep process'
        cfg_fn, log_fn = prepare_format(out, base_args, d, K, overrides)
        print(f'  ▸ Format {data_name(d)} K={K}  (log: {log_fn})', flush=True)
        t0 = time.time()
        rc = run_phyddle(cmd, cfg_fn, log_fn, env=env)
        return finish_format(out, base_args, d, K, rc, time.time() - t0)

